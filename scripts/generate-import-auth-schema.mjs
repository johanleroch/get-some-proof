import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { convexAdapter } from "@convex-dev/better-auth";
import { format, resolveConfig } from "prettier";
import { createImportOAuthOptions } from "../convex/importOAuthOptions.ts";

const require = createRequire(import.meta.url);
const componentDir = resolve("convex/betterAuth");
await mkdir(componentDir, { recursive: true });

async function writeSchema(name, source) {
  const filepath = resolve(componentDir, name);
  const documented = source.replace(
    /\/\*\*[\s\S]*?\*\//,
    `/**
 * Generated by scripts/generate-import-auth-schema.mjs using the pinned
 * @convex-dev/better-auth adapter. Do not edit manually.
 * Regenerate with: pnpm generate:import-auth-schema
 */`,
  );
  await writeFile(
    filepath,
    await format(documented, { ...(await resolveConfig(filepath)), filepath }),
  );
}

// Preserve every table and field from the pinned component when changing its
// source directory. In particular, never reinterpret its legacy OAuth tables.
const packageDir = dirname(
  require.resolve("@convex-dev/better-auth/package.json"),
);
const legacy = await readFile(
  resolve(packageDir, "src/component/schema.ts"),
  "utf8",
);
await writeSchema("legacySchema.ts", legacy);

// The adapter's own generator handles dates, nullability, arrays and indexes.
// Neither database placeholder is accessed during schema generation.
const database = convexAdapter({}, {});
const options = {
  ...createImportOAuthOptions({
    siteUrl: "https://schema-generation.invalid",
    secret: "schema-generation-only-no-runtime-credential",
    database,
  }),
  user: { additionalFields: { userId: { type: "string", required: false } } },
};
const generated = await database(options).createSchema(
  options,
  "convex/betterAuth/importOAuthSchema.ts",
);
await writeSchema("importOAuthSchema.ts", generated.code);
console.log(
  "Generated the preserved Better Auth schema and four import OAuth tables.",
);
