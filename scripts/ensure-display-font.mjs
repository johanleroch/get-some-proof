// Generates src/app/fonts/display-font.ts before dev, build and typecheck.
//
// Gelica is a licensed font (DESIGN.md section 3): its files live in
// src/app/fonts/gelica/ on each machine and never in this public repository.
// next/font/local needs literal paths at build time, so this script writes a
// module that loads Gelica when the five files are present and falls back to
// Figtree (the body face) when they are not, with a warning. CI and fresh
// clones build either way.
import { access, mkdir, writeFile } from "node:fs/promises";

const faces = [
  ["Gelica-Regular.otf", "400"],
  ["Gelica-Medium.otf", "500"],
  ["Gelica-SemiBold.otf", "600"],
  ["Gelica-Bold.otf", "700"],
  ["Gelica-Black.otf", "900"],
];
const fontsDirectory = new URL("../src/app/fonts/gelica/", import.meta.url);
const destination = new URL(
  "../src/app/fonts/display-font.ts",
  import.meta.url,
);

const present = (
  await Promise.all(
    faces.map(([file]) =>
      access(new URL(file, fontsDirectory)).then(
        () => true,
        () => false,
      ),
    ),
  )
).every(Boolean);

const header = `// Generated by scripts/ensure-display-font.mjs before dev, build and
// typecheck. Ignored by git and rewritten from the font files present.
`;

const withGelica = `${header}import localFont from "next/font/local";

/** Gelica, the licensed display face, self-hosted (DESIGN.md section 3). */
export const displayFont = localFont({
  display: "swap",
  src: [
${faces.map(([file, weight]) => `    { path: "./gelica/${file}", weight: "${weight}" },`).join("\n")}
  ],
  variable: "--font-gelica",
});
`;

const withoutGelica = `${header}
/**
 * Gelica is missing on this machine, so every display style falls back to
 * Figtree through the font stacks in globals.css. Put the five OTF files in
 * src/app/fonts/gelica/ and run the script again to get the display face.
 */
export const displayFont = { variable: "" };
`;

// A fresh checkout has no src/app/fonts/ at all: its only content is ignored.
await mkdir(new URL("./", destination), { recursive: true });
await writeFile(destination, present ? withGelica : withoutGelica);
if (!present) {
  console.warn(
    "[display-font] Gelica not found in src/app/fonts/gelica/: headings fall back to Figtree.",
  );
}
